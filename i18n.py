def weather_name(code: int, lang: str) -> str:
    idx = {"en": 0, "hi": 1, "bho": 2}.get(lang, 0)
    # nearest fallback
    if code in WEATHER_NAMES:
        return WEATHER_NAMES[code][idx]
    # group fallback
    for k in sorted(WEATHER_NAMES):
        if code <= k:
            return WEATHER_NAMES[k][idx]
    return WEATHER_NAMES[0][idx]

